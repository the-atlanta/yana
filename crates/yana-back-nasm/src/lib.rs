//! NASM text backend (§13): IR → NASM assembly.
//!
//! Doubles as the test oracle: `yana oracle` assembles this output with nasm(1)
//! and compares the disassembly against the iced backend. Mnemonics, operand
//! order and registers must match exactly; displacement *values* legitimately
//! differ (the two linkers place sections differently), so the oracle
//! normalizes numeric fields away.
//!
//! Comments are preserved (§1/§13): trivia from the lexer rides along, and
//! symbol names appear as `; name` annotations.

use std::collections::HashMap;
use std::fmt::Write as _;

use yana_ast::place::SectionKind;
use yana_ast::reg::Reg;
use yana_codegen::insn::jcc_mnemonic;
use yana_codegen::{
    DataItem, Displacement, Insn, MemOp, Module, Operand, SymbolKind, WideOp,
};

/// Emit NASM source for a module. `comments` = `(byte_offset, text)` trivia.
pub fn emit(module: &Module, comments: &[(u32, String)]) -> String {
    let mut out = String::new();
    writeln!(out, "; generated by yana — do not edit").unwrap();
    writeln!(out, "bits 64").unwrap();
    // symbol references are rip-relative by default; matches the iced backend's
    // rip+disp32 encoding so both link to the same instruction shapes.
    writeln!(out, "default rel").unwrap();

    for (_, c) in comments {
        writeln!(out, ";{c}").unwrap();
    }

    // ---- data sections ----
    for sec in &module.sections {
        match sec.kind {
            SectionKind::Text => {}
            SectionKind::Bss => {
                writeln!(out, "\nsection .bss").unwrap();
                for item in &sec.items {
                    if let DataItem::Zero { size, align, sym, .. } = item {
                        if *align > 1 {
                            writeln!(out, "align {align}").unwrap();
                        }
                        if let Some(s) = sym {
                            writeln!(out, "{}:", module.symbols[*s].name).unwrap();
                        }
                        writeln!(out, "resb {size}").unwrap();
                    }
                }
            }
            kind => {
                writeln!(out, "\nsection {}", kind.name()).unwrap();
                for item in &sec.items {
                    if let DataItem::Bytes { bytes, align, sym, .. } = item {
                        if *align > 1 {
                            writeln!(out, "align {align}").unwrap();
                        }
                        if let Some(s) = sym {
                            writeln!(out, "{}:", module.symbols[*s].name).unwrap();
                        }
                        writeln!(out, "db {}", bytes_str(bytes)).unwrap();
                    }
                }
            }
        }
    }

    // ---- text ----
    writeln!(out, "\nsection .text").unwrap();
    // export directives first (NASM wants `global` before use)
    for body in &module.bodies {
        let sym = &module.symbols[body.symbol];
        if sym.exported {
            writeln!(out, "global {}", sym.name).unwrap();
        }
    }
    // extern declarations for undefined symbols referenced by calls
    for (i, sym) in module.symbols.iter().enumerate() {
        if matches!(sym.kind, SymbolKind::ExternFn) && sym.syscall.is_none() && is_called(module, i)
        {
            writeln!(out, "extern {}", sym.name).unwrap();
        }
    }

    for body in &module.bodies {
        let sym = &module.symbols[body.symbol];
        writeln!(out, "\n{}:", sym.name).unwrap();

        // label index → nasm label name
        let mut labels: HashMap<usize, String> = HashMap::new();
        for (idx, def) in body.label_defs.iter().enumerate() {
            labels.insert(idx, format!(".L{}_{}", sanitize(&sym.name), sanitize(&def.name)));
        }
        // at_insn index → label indices to emit before that instruction
        let mut at: HashMap<usize, Vec<usize>> = HashMap::new();
        for (idx, def) in body.label_defs.iter().enumerate() {
            at.entry(def.at_insn.min(body.insns.len())).or_default().push(idx);
        }

        for (i, si) in body.insns.iter().enumerate() {
            if let Some(ls) = at.get(&i) {
                for l in ls {
                    writeln!(out, "{}:", labels[l]).unwrap();
                }
            }
            if let Some((_, c)) = &si.comment {
                writeln!(out, "    ;{c}").unwrap();
            }
            writeln!(out, "    {}", insn_to_nasm(&si.insn, module, &labels)).unwrap();
        }
        if let Some(ls) = at.get(&body.insns.len()) {
            for l in ls {
                writeln!(out, "{}:", labels[l]).unwrap();
            }
        }
    }

    out
}

fn is_called(module: &Module, sym: usize) -> bool {
    module
        .bodies
        .iter()
        .flat_map(|b| b.insns.iter())
        .any(|i| matches!(&i.insn, Insn::Call { sym: s, .. } if *s == sym))
}

fn sanitize(s: &str) -> String {
    s.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect()
}

fn bytes_str(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ")
}

/// One IR instruction → one NASM line (§0: visible expansion).
fn insn_to_nasm(ins: &Insn, module: &Module, labels: &HashMap<usize, String>) -> String {
    match ins {
        Insn::Mov { dst, src, size } => {
            let d = operand_str(dst, module, *size);
            let s = operand_str(src, module, *size);
            // Note: NASM optimizes `mov r64, imm32` to the 32-bit form
            // (zero-extends, semantically identical). The oracle normalizes
            // 64/32-bit GPR names so this legitimate difference is not a diff.
            format!("mov {d}, {s}")
        }
        Insn::Movzx { dst, src, src_size, .. } => {
            format!("movzx {}, {}", reg_str(*dst), operand_str(src, module, *src_size))
        }
        Insn::Movsx { dst, src, src_size, dst_size } => {
            let mnem = if *dst_size == 64 && *src_size == 32 { "movsxd" } else { "movsx" };
            format!("{mnem} {}, {}", reg_str(*dst), operand_str(src, module, *src_size))
        }
        Insn::Lea { dst, addr } => format!("lea {}, {}", reg_str(*dst), mem_str(addr, module)),
        Insn::LeaSym { dst, sym, add } => {
            let name = &module.symbols[*sym].name;
            let disp = if *add == 0 { String::new() } else { format!("{:+}", *add) };
            format!("lea {}, [rel {name}{disp}]", reg_str(*dst))
        }
        Insn::Push { src, size } => format!("push {}", operand_str(src, module, *size)),
        Insn::Pop { dst, size } => format!("pop {}", operand_str(dst, module, *size)),
        Insn::StackSlot { grow } => {
            // `_` slot (§4.3): `lea rsp,[rsp ∓ 8]` — flags untouched. Must match
            // the iced backend byte-for-byte.
            if *grow {
                "lea rsp, [rsp-8]".to_string()
            } else {
                "lea rsp, [rsp+8]".to_string()
            }
        }
        Insn::Xchg { a, b, size } => {
            format!("xchg {}, {}", operand_str(a, module, *size), operand_str(b, module, *size))
        }
        Insn::Add { dst, src, size } => alu("add", dst, src, module, *size),
        Insn::Sub { dst, src, size } => alu("sub", dst, src, module, *size),
        Insn::And { dst, src, size } => alu("and", dst, src, module, *size),
        Insn::Or { dst, src, size } => alu("or", dst, src, module, *size),
        Insn::Xor { dst, src, size } => alu("xor", dst, src, module, *size),
        Insn::Shl { dst, src, size } => shift("shl", dst, src, module, *size),
        Insn::Shr { dst, src, size } => shift("shr", dst, src, module, *size),
        Insn::Imul2 { dst, src, size } => alu("imul", dst, src, module, *size),
        Insn::Neg { dst, size } => format!("neg {}", operand_str(dst, module, *size)),
        Insn::Not { dst, size } => format!("not {}", operand_str(dst, module, *size)),
        Insn::Inc { dst, size } => format!("inc {}", operand_str(dst, module, *size)),
        Insn::Dec { dst, size } => format!("dec {}", operand_str(dst, module, *size)),
        Insn::Cmp { a, b, size } => {
            format!("cmp {}, {}", operand_str(a, module, *size), operand_str(b, module, *size))
        }
        Insn::MulWide { src, signed, size } => {
            let m = if *signed { "imul" } else { "mul" };
            format!("{m} {}", operand_str(src, module, *size))
        }
        Insn::DivWide { src, op, size } => {
            let m = match op { WideOp::Unsigned => "div", WideOp::Signed => "idiv" };
            format!("{m} {}", operand_str(src, module, *size))
        }
        Insn::ExtendPair { signed, size } => {
            if *signed {
                if *size == 64 { "cqo".to_string() } else { "cdq".to_string() }
            } else {
                let r = if *size == 32 { "edx" } else { "rdx" };
                format!("xor {r}, {r}")
            }
        }
        Insn::Jmp { label } => format!("jmp {}", label_name(*label, labels)),
        Insn::Jcc { cc, label } => format!("{} {}", jcc_mnemonic(*cc), label_name(*label, labels)),
        Insn::Call { sym, .. } => format!("call {}", module.symbols[*sym].name),
        Insn::Syscall => "syscall".to_string(),
        Insn::Ret => "ret".to_string(),
        Insn::Int3 => "int3".to_string(),
        Insn::Nop => "nop".to_string(),
    }
}

fn label_name(idx: usize, labels: &HashMap<usize, String>) -> String {
    labels.get(&idx).cloned().unwrap_or_else(|| format!(".L{idx}"))
}

fn alu(m: &str, dst: &Operand, src: &Operand, module: &Module, size: u32) -> String {
    format!("{m} {}, {}", operand_str(dst, module, size), operand_str(src, module, size))
}

fn shift(m: &str, dst: &Operand, src: &Operand, module: &Module, size: u32) -> String {
    let s = match src {
        Operand::Imm(v) => v.to_string(),
        Operand::Reg(r) if r.name() == "cl" => "cl".to_string(),
        _ => "0".to_string(), // resolver guarantees imm-or-cl
    };
    format!("{m} {}, {s}", operand_str(dst, module, size))
}

fn operand_str(o: &Operand, module: &Module, size: u32) -> String {
    match o {
        Operand::Reg(r) => reg_str(*r),
        Operand::Imm(v) => imm_str(*v),
        Operand::Mem(m) => mem_str(m, module),
        Operand::Sym { sym, add } => {
            let name = &module.symbols[*sym].name;
            if *add == 0 { name.clone() } else { format!("{name}{:+}", *add) }
        }
    }
}

fn reg_str(r: Reg) -> String {
    r.name().to_string()
}

fn imm_str(v: i64) -> String {
    if v < 0 {
        format!("{v}")
    } else if v > 9 {
        format!("0x{v:x}")
    } else {
        format!("{v}")
    }
}

/// NASM memory operand `[base + index*scale + disp]`. Symbol displacements use
/// `[rel name]` (default rel is on) to match the iced rip-relative encoding.
fn mem_str(m: &MemOp, module: &Module) -> String {
    let mut parts: Vec<String> = Vec::new();
    let mut disp = match &m.disp {
        Displacement::Const(c) => *c,
        Displacement::Sym { sym, add } => {
            parts.push(format!("rel {}", module.symbols[*sym].name));
            *add
        }
    };
    if let Some(b) = m.base {
        parts.push(reg_str(b));
    }
    if let Some(i) = m.index {
        if m.scale == 1 {
            parts.push(reg_str(i));
        } else {
            parts.push(format!("{}*{}", reg_str(i), m.scale));
        }
    }
    // rip-relative with no base/index and a constant disp still needs the disp
    if parts.is_empty() {
        parts.push(format!("{disp}"));
        disp = 0;
    }
    let mut inner = parts.join("+");
    if disp != 0 {
        inner = format!("{inner}{disp:+}");
    }
    format!("[{inner}]")
}

/// `yana expand` — a readable IR dump (one instruction per line).
pub fn expand_ir(module: &Module) -> String {
    let mut out = String::new();
    for s in &module.sections {
        writeln!(out, "section {}:", s.kind.name()).unwrap();
        for item in &s.items {
            match item {
                DataItem::Bytes { offset, bytes, align, .. } => {
                    writeln!(out, "  @{offset} align {align}: {} bytes", bytes.len()).unwrap();
                }
                DataItem::Zero { offset, size, align, .. } => {
                    writeln!(out, "  @{offset} align {align}: zero {size}").unwrap();
                }
            }
        }
    }
    for (i, sym) in module.symbols.iter().enumerate() {
        let kind = match &sym.kind {
            SymbolKind::Function { body_index } => format!("fn body={body_index}"),
            SymbolKind::ExternFn => match sym.syscall {
                Some(n) => format!("extern syscall({n})"),
                None => "extern".to_string(),
            },
            SymbolKind::Static { section, offset, size } => {
                format!("static {} @{offset} size={size}", section.name())
            }
            SymbolKind::Const { value } => format!("const {value}"),
        };
        let exp = if sym.exported { " global" } else { "" };
        writeln!(out, "sym #{i} {} [{kind}{exp}]", sym.name).unwrap();
    }
    if let Some(e) = module.entry {
        writeln!(out, "entry: sym #{e} ({})", module.symbols[e].name).unwrap();
    }
    for body in &module.bodies {
        writeln!(out, "\nfn {} (sym #{}):", module.symbols[body.symbol].name, body.symbol).unwrap();
        for def in &body.label_defs {
            writeln!(out, "  label '{} -> insn #{}", def.name, def.at_insn).unwrap();
        }
        for (i, si) in body.insns.iter().enumerate() {
            writeln!(out, "  {i:>4}: {}", nasm_line_dbg(&si.insn, module, body)).unwrap();
        }
    }
    out
}

fn nasm_line_dbg(ins: &Insn, module: &Module, body: &yana_codegen::FnBody) -> String {
    let labels: HashMap<usize, String> = body
        .label_defs
        .iter()
        .enumerate()
        .map(|(i, d)| (i, format!("'{}", d.name)))
        .collect();
    insn_to_nasm(ins, module, &labels)
}
