//! Documentation for the Linux x86-64 syscalls reachable through
//! `#[syscall(N)]` (§5.5).
//!
//! The hover for a syscall number renders exactly this table: name,
//! C signature, per-register arguments, return value and the man page.
//! Numbers follow the x86-64 Linux ABI (`arch/x86/entry/syscalls/syscall_64.tbl`);
//! the calling convention is §5.5: `rax` = number, `rdi, rsi, rdx, r10, r8, r9`
//! = arguments, `rax` = result, clobbered `rcx`/`r11`.

/// One syscall argument: which register carries it and what it means.
pub struct Arg {
    /// Register per the Linux x86-64 syscall ABI.
    pub reg: &'static str,
    /// Parameter name from the C prototype.
    pub name: &'static str,
    /// C-level type (`u64`, `*u8`, `i64`, …).
    pub ty: &'static str,
    /// Short human explanation.
    pub doc: &'static str,
}

/// One documented syscall.
pub struct Syscall {
    pub nr: i64,
    pub name: &'static str,
    /// C prototype as in the man page.
    pub signature: &'static str,
    pub args: &'static [Arg],
    /// Return value / error convention.
    pub returns: &'static str,
    /// What it does.
    pub summary: &'static str,
    /// Man page reference.
    pub man: &'static str,
}

/// Look up a syscall by number (x86-64 Linux).
pub fn by_number(nr: i64) -> Option<&'static Syscall> {
    SYSCALLS.iter().find(|s| s.nr == nr)
}

/// Look up a syscall by name (e.g. `write`).
pub fn by_name(name: &str) -> Option<&'static Syscall> {
    SYSCALLS.iter().find(|s| s.name == name)
}

/// Name for a syscall number, for inlay hints.
pub fn name_of(nr: i64) -> Option<&'static str> {
    by_number(nr).map(|s| s.name)
}

